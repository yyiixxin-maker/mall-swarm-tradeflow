    @Override
    public ConfirmOrderResult generateConfirmOrder(List<Long> cartIds) {
        ConfirmOrderResult result = new ConfirmOrderResult();
        //获取购物车信息
        UmsMember currentMember = memberService.getCurrentMember();
        List<CartPromotionItem> cartPromotionItemList = cartItemService.listPromotion(currentMember.getId(),cartIds);
        result.setCartPromotionItemList(cartPromotionItemList);
        //获取用户收货地址列表
        List<UmsMemberReceiveAddress> memberReceiveAddressList = memberReceiveAddressService.list();
        result.setMemberReceiveAddressList(memberReceiveAddressList);
        //获取用户可用优惠券列表
        List<SmsCouponHistoryDetail> couponHistoryDetailList = memberCouponService.listCart(cartPromotionItemList, 1);
        result.setCouponHistoryDetailList(couponHistoryDetailList);
        //获取用户积分
        result.setMemberIntegration(currentMember.getIntegration());
        //获取积分使用规则
        UmsIntegrationConsumeSetting integrationConsumeSetting = integrationConsumeSettingMapper.selectByPrimaryKey(1L);
        result.setIntegrationConsumeSetting(integrationConsumeSetting);
        //计算总金额、活动优惠、应付金额
        ConfirmOrderResult.CalcAmount calcAmount = calcCartAmount(cartPromotionItemList);
        result.setCalcAmount(calcAmount);
        return result;
    }

    @Override
    public Map<String, Object> generateOrder(OrderParam orderParam) {
        validateOrderParam(orderParam);
        UmsMember currentMember = memberService.getCurrentMember();
        String hash = requestHash(orderParam);
        tradeDao.claimRequest(currentMember.getId(), orderParam.getRequestKey(), hash);
        OrderRequest request = tradeDao.lockRequest(currentMember.getId(), orderParam.getRequestKey());
        if (!hash.equals(request.getRequestHash())) Asserts.fail("幂等键已用于不同的结算请求");
        if (request.getOrderId() != null) return orderResult(request.getOrderId());
        List<Long> lockedCart = tradeDao.lockCart(currentMember.getId(), orderParam.getCartIds());
        if (lockedCart.size() != orderParam.getCartIds().size()) Asserts.fail("所选购物车商品不存在或已经结算");
        currentMember = memberService.getById(currentMember.getId());
        List<OmsOrderItem> orderItemList = new ArrayList<>();
        //获取购物车及优惠信息
        List<CartPromotionItem> cartPromotionItemList = cartItemService.listPromotion(currentMember.getId(), orderParam.getCartIds());
        if (cartPromotionItemList.size() != lockedCart.size()) Asserts.fail("购物车商品已发生变化，请重新结算");
        for (CartPromotionItem cartPromotionItem : cartPromotionItemList) {
            //生成下单商品信息
            OmsOrderItem orderItem = new OmsOrderItem();
            orderItem.setProductId(cartPromotionItem.getProductId());
            orderItem.setProductName(cartPromotionItem.getProductName());
            orderItem.setProductPic(cartPromotionItem.getProductPic());
            orderItem.setProductAttr(cartPromotionItem.getProductAttr());
            orderItem.setProductBrand(cartPromotionItem.getProductBrand());
            orderItem.setProductSn(cartPromotionItem.getProductSn());
            orderItem.setProductPrice(cartPromotionItem.getPrice());
            orderItem.setProductQuantity(cartPromotionItem.getQuantity());
            orderItem.setProductSkuId(cartPromotionItem.getProductSkuId());
            orderItem.setProductSkuCode(cartPromotionItem.getProductSkuCode());
            orderItem.setProductCategoryId(cartPromotionItem.getProductCategoryId());
            orderItem.setPromotionAmount(cartPromotionItem.getReduceAmount());
            orderItem.setPromotionName(cartPromotionItem.getPromotionMessage());
            orderItem.setGiftIntegration(cartPromotionItem.getIntegration());
            orderItem.setGiftGrowth(cartPromotionItem.getGrowth());
            orderItemList.add(orderItem);
        }
        orderStateService.reserve(orderItemList);
        SmsCouponHistoryDetail selectedCoupon = null;
        //判断使用使用了优惠券
        if (orderParam.getCouponId() == null) {
            //不用优惠券
            for (OmsOrderItem orderItem : orderItemList) {
                orderItem.setCouponAmount(new BigDecimal(0));
            }
        } else {
            //使用优惠券
            SmsCouponHistoryDetail couponHistoryDetail = getUseCoupon(cartPromotionItemList, orderParam.getCouponId());
            if (couponHistoryDetail == null) {
                Asserts.fail("该优惠券不可用");
            }
            //对下单商品的优惠券进行处理
            handleCouponAmount(orderItemList, couponHistoryDetail);
            selectedCoupon = couponHistoryDetail;
        }
        //判断是否使用积分
        if (orderParam.getUseIntegration() == null||orderParam.getUseIntegration().equals(0)) {
            //不使用积分
            for (OmsOrderItem orderItem : orderItemList) {
                orderItem.setIntegrationAmount(new BigDecimal(0));
            }
        } else {
            //使用积分
            BigDecimal totalAmount = calcTotalAmount(orderItemList);
            BigDecimal integrationAmount = getUseIntegrationAmount(orderParam.getUseIntegration(), totalAmount, currentMember, orderParam.getCouponId() != null);
            if (integrationAmount.compareTo(new BigDecimal(0)) == 0) {
                Asserts.fail("积分不可用");
            } else {
                //可用情况下分摊到可用商品中
                for (OmsOrderItem orderItem : orderItemList) {
                    BigDecimal perAmount = orderItem.getProductPrice().divide(totalAmount, 3, RoundingMode.HALF_EVEN).multiply(integrationAmount);
                    orderItem.setIntegrationAmount(perAmount);
                }
            }
        }
        //计算order_item的实付金额
        handleRealAmount(orderItemList);
        //根据商品合计、运费、活动优惠、优惠券、积分计算应付金额
        OmsOrder order = new OmsOrder();
        order.setDiscountAmount(new BigDecimal(0));
        order.setTotalAmount(calcTotalAmount(orderItemList));
        order.setFreightAmount(new BigDecimal(0));
        order.setPromotionAmount(calcPromotionAmount(orderItemList));
        order.setPromotionInfo(getOrderPromotionInfo(orderItemList));
        if (orderParam.getCouponId() == null) {
            order.setCouponAmount(new BigDecimal(0));
        } else {
            order.setCouponId(orderParam.getCouponId());
            order.setCouponAmount(calcCouponAmount(orderItemList));
        }
        order.setIntegrationAmount(calcIntegrationAmount(orderItemList));
        order.setPayAmount(calcPayAmount(order).setScale(2, RoundingMode.HALF_UP));
        if (order.getPayAmount().signum() <= 0) Asserts.fail("订单应付金额必须大于零");
        order.setUseIntegration(orderParam.getUseIntegration());
        //转化为订单信息并插入数据库
        order.setMemberId(currentMember.getId());
        order.setCreateTime(new Date());
        order.setMemberUsername(currentMember.getUsername());
        //支付方式：0->未支付；1->支付宝；2->微信
        order.setPayType(orderParam.getPayType());
        //订单来源：0->PC订单；1->app订单
        order.setSourceType(1);
        //订单状态：0->待付款；1->待发货；2->已发货；3->已完成；4->已关闭；5->无效订单
        order.setStatus(0);
        //订单类型：0->正常订单；1->秒杀订单
        order.setOrderType(0);
        //收货人信息：姓名、电话、邮编、地址
        UmsMemberReceiveAddress address = memberReceiveAddressService.getItem(orderParam.getMemberReceiveAddressId());
        if (address == null) Asserts.fail("收货地址不存在或无权使用");
        order.setReceiverName(address.getName());
        order.setReceiverPhone(address.getPhoneNumber());
        order.setReceiverPostCode(address.getPostCode());
        order.setReceiverProvince(address.getProvince());
        order.setReceiverCity(address.getCity());
        order.setReceiverRegion(address.getRegion());
        order.setReceiverDetailAddress(address.getDetailAddress());
        //0->未确认；1->已确认
        order.setConfirmStatus(0);
        order.setDeleteStatus(0);
        //计算赠送积分
        order.setIntegration(calcGifIntegration(orderItemList));
        //计算赠送成长值
        order.setGrowth(calcGiftGrowth(orderItemList));
        //生成订单号
        order.setOrderSn(UUID.randomUUID().toString().replace("-", ""));
        //设置自动收货天数
        List<OmsOrderSetting> orderSettings = orderSettingMapper.selectByExample(new OmsOrderSettingExample());
        if(CollUtil.isNotEmpty(orderSettings)){
            order.setAutoConfirmDay(orderSettings.get(0).getConfirmOvertime());
        }
        // TODO: 2018/9/3 bill_*,delivery_*
        //插入order表和order_item表
        orderMapper.insert(order);
        for (OmsOrderItem orderItem : orderItemList) {
            orderItem.setOrderId(order.getId());
            orderItem.setOrderSn(order.getOrderSn());
        }
        orderItemDao.insertList(orderItemList);
        //如使用优惠券更新优惠券使用状态
        if (selectedCoupon != null) {
            if (tradeDao.useCoupon(selectedCoupon.getId(), currentMember.getId(), order.getId(), order.getOrderSn(), new Date()) != 1) {
                Asserts.fail("优惠券已被使用，请重新结算");
            }
        }
        //如使用积分需要扣除积分
        if (orderParam.getUseIntegration() > 0) {
            if (tradeDao.spendPoints(currentMember.getId(), orderParam.getUseIntegration()) != 1) Asserts.fail("积分不足");
            orderStateService.evictMemberAfterCommit(currentMember.getId());
        }
        //删除购物车中的下单商品
        deleteCartItemList(cartPromotionItemList, currentMember);
        //发送延迟消息取消订单
        enqueueTimeout(order);
        if (tradeDao.completeRequest(currentMember.getId(), orderParam.getRequestKey(), order.getId()) != 1) Asserts.fail("结算请求状态异常");
        Map<String, Object> result = new HashMap<>();
        result.put("order", order);
        result.put("orderItemList", orderItemList);
        return result;
    }

    @Override
    public Integer paySuccess(Long orderId, Integer payType) {
        OmsOrder order = ownedOrder(orderId);
        if (!Integer.valueOf(1).equals(payType)) Asserts.fail("当前仅支持经支付宝查询确认支付");
        String status = alipayService.query(order.getOrderSn(), null);
        PaymentTransaction payment = tradeDao.payment(order.getOrderSn());
        if (!("TRADE_SUCCESS".equals(status) || "TRADE_FINISHED".equals(status))
                || payment == null || !"APPLIED".equals(payment.getState())) Asserts.fail("支付尚未确认或需要人工核对");
        return 1;
    }

    @Override
    public Integer cancelTimeOutOrder() {
        int count = 0;
        for (Long id : tradeDao.overdue(System.currentTimeMillis())) {
            try { count += orderStateService.cancel(id, null, true, "SYSTEM", "超时关闭订单"); }
            catch (RuntimeException e) {
                org.slf4j.LoggerFactory.getLogger(getClass()).warn("Timeout cancellation needs retry/review: orderId={}, error={}", id, e.getClass().getSimpleName());
            }
        }
        return count;
    }

